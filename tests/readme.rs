//! The README's harness table is generated from the registry; keep them equal.

#[test]
fn readme_lists_exactly_the_registry() {
    let readme = include_str!("../README.md");
    let begin = "<!-- harnesses:begin (generated by `harnesscfg agents --format markdown`) -->\n";
    let start = readme.find(begin).expect("begin marker") + begin.len();
    let stop = readme.find("<!-- harnesses:end -->").expect("end marker");
    let expected = harnesscfg::cli::markdown(&harnesscfg::registry::all().unwrap());
    assert_eq!(
        &readme[start..stop],
        expected,
        "regenerate with `harnesscfg agents --format markdown`"
    );
}
